async function seed() {
  console.log(`Seeding ${guides.length} guides...`);

  for (const guide of guides) {
    const row = {
      ...guide,
      status: "published",
      published_at: new Date().toISOString(),
    };

    const { data: existing } = await supabase
      .from("buying_guides")
      .select("id")
      .eq("slug", guide.slug)
      .maybeSingle();

    if (existing && !FORCE) {
      console.log(`  ⏭  ${guide.slug} (exists, skipping)`);
      continue;
    }

    if (existing && FORCE) {
      const { error } = await supabase
        .from("buying_guides")
        .update(row)
        .eq("id", existing.id);
      if (error) console.error(`  ✗ ${guide.slug}:`, error.message);
      else console.log(`  ↻ ${guide.slug} (updated)`);
    } else {
      const { error } = await supabase.from("buying_guides").insert(row);
      if (error) console.error(`  ✗ ${guide.slug}:`, error.message);
      else console.log(`  ✓ ${guide.slug} (inserted)`);
    }
  }

  console.log("\nDone.");
}

await seed();
