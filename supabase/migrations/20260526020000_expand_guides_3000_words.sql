## الأسئلة الشائعة

### السؤال: هل أمازون السعودية = أمازون.com الأمريكي؟

لا. أمازون السعودية (amazon.sa) منصّة منفصلة بمخزون وأسعار محلّية. ممكن تجد منتجات مستوردة مباشرة من أمازون أمريكا عبر برنامج "Amazon Global"، لكن السعر يشمل شحن دولي ورسوم جمركية محتملة. أغلب المنتجات على amazon.sa من المخزون السعودي.

### السؤال: متى تكون عروض Yellow Friday من نون أفضل من Black Friday من أمازون؟

غالباً Yellow Friday تنطلق قبل Black Friday ببضعة أيام وتركّز على الموضة، الجمال، الأجهزة المنزلية الصغيرة. أمازون Black Friday أقوى في الإلكترونيات والكتب. القاعدة: لو تبي عطر أو ملابس، استنّى Yellow Friday. لو تبي لابتوب أو سمّاعة Bose، Black Friday أمازون أفضل.

### السؤال: كيف أعرف لو الكوبون مفعّل قبل إتمام الدفع؟

في صفحة "ملخص الطلب" قبل زر "ادفع"، لازم تشوف سطر اسمه "الخصم" أو "الكوبون المطبّق" بقيمة سالبة. لو ما ظهر، الكوبون مو مفعّل. ارجع للسلة، اضغط على "إضافة كود الخصم"، وأعد المحاولة.

### السؤال: ما الفرق بين Prime وnoon One؟ أيهما يستحق؟

Prime أغلى (١٤٠ ريال سنوياً) لكن يشمل Prime Video. noon One أرخص (٥٩ ريال سنوياً) ومركّز على الشحن والخصومات بدون محتوى ترفيهي. إذا تتسوّق من نون أكثر، اختار noon One. إذا تحب Prime Video وتشتري كثير من أمازون، Prime منطقي. لا حرج في الاشتراك في الاثنين.

### السؤال: هل آمن ربط بطاقة مدى مع المنصّتين؟

نعم. الاثنين معتمدان من مدى ويستخدمان تشفير قياسي ٣D Secure. كذلك تقدر تستخدم Apple Pay أو STC Pay لطبقة حماية إضافية بدون إدخال رقم البطاقة مباشرة.

### السؤال: متى يكون شراء "Amazon Renewed" قرار خاطئ؟

لمّا تشتري هاتف ذكي راقي عمره أكثر من سنتين — البطارية ممكن تكون متآكلة. كذلك تجنّب شراء أجهزة العناية الشخصية (شفّاطات حليب، أجهزة إزالة شعر) مجدّدة. للابتوبات والآيباد المجدّد، عادة قرار ذكي إذا الضمان ٩٠ يوم على الأقل.

### السؤال: الإرجاع المجاني، هل فعلاً مجاني؟ ما الحالات الاستثنائية؟

في أمازون: الإرجاع مجاني لأغلب المنتجات اللي تبيعها أمازون نفسها خلال ٣٠ يوم. الاستثناءات: المنتجات المخصّصة، الطعام، الأدوية، المنتجات الحميمية. في نون: مجاني لأغلب المنتجات خلال ١٥ يوم، لكن أحياناً يخصمون رسوم استرجاع للمنتجات الكبيرة الحجم (أجهزة منزلية كبيرة).

### السؤال: كيف أتابع طلب يأخذ وقت أطول من المتوقّع؟

في أمازون: اذهب لـ "طلباتي"، اضغط على الطلب، ثم "الحصول على المساعدة" أو "تواصل مع البائع". الردّ خلال ساعات. في نون: في تطبيق نون، اضغط على الطلب ثم "تحتاج مساعدة" واختر "تأخّر الطلب". الشات المباشر يردّ خلال ١٥ دقيقة في الغالب.

### السؤال: هل أحصل على ضمان الوكيل لو اشتريت من أمازون؟

ليس دائماً. ضمان الوكيل المحلّي يعتمد على البائع. إذا "Sold by Amazon" والمنتج مستورد من خارج السعودية، الضمان قد يكون دولي فقط. تحقّق دائماً من وصف المنتج عن نوع الضمان قبل الشراء، خصوصاً للأجهزة باهظة الثمن.

### السؤال: أيهما أفضل لشراء الهواتف الذكية حديثة الإصدار؟

عادة متعادل. للأجهزة اللي يطلقها سامسونج وآبل، الفرق ٠–٥٪. الأهم تتحقّق من نوع الضمان (وكيل سعودي أو دولي) ومن البائع (Sold by Amazon أو Sold by noon Direct يفضّل عن البائعين الخارجيين).

### السؤال: متى أستخدم نون Food بدلاً من تطبيقات التوصيل الأخرى؟

عندما يكون عندك اشتراك noon One، أو لمّا تكون عروض المطعم على نون Food أقوى من المنافسين. كذلك إذا تطلب بقالة + وجبة في نفس الوقت، نون يجمع التوصيل أحياناً. غير ذلك، قارن مع [هنقرستيشن](/stores/hungerstation) و[جاهز](/stores/jahez) لكل وجبة.

### السؤال: هل أستفيد من فترة التجربة المجانية لـ Prime / noon One أكثر من مرة؟

عادة لا. كل بطاقة وعنوان مرتبط بحساب واحد، والمنصّتين يكتشفان محاولات إعادة الاشتراك من نفس البيانات. تجربة Prime متوفّرة ٣٠ يوم مرة واحدة، وتجربة noon One حالياً بضعة أيام حسب العرض.

