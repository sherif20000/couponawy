**خانق المعالج (Throttling):** ظاهرة تحدث عندما يسخن المعالج فيخفّض الأداء لحماية نفسه. تظهر بوضوح بعد ١٥-٢٠ دقيقة لعب ثقيل. الفلاجشب تخنق ٢٠-٣٠٪ فقط، بينما الأجهزة الرخيصة قد تخنق ٥٠-٦٠٪ — يعني نص الأداء. لو تلعب PUBG أو Genshin Impact، هذا الرقم يهمك جداً.

**نصيحة عملية:** قبل أن تشتري، ابحث في YouTube عن "اسم المعالج + throttling test". في خمس دقائق تعرف هل سيخدمك في اللعب أم لا.

## الكاميرا: ما تحتاج أن تعرفه أبعد من الميجابكسلات

السوق يبيعك أرقاماً — ٢٠٠ ميجابكسل، ١٠٨ ميجابكسل، ٥٠ ميجابكسل. الرقم لا يعني شيئاً لوحده. السر في **حجم الحساس (Sensor Size)**.

حسّاس بحجم ١/١٫٣ إنش بدقّة ٥٠ ميجابكسل (مثل Pixel 8 أو iPhone 15 Pro) يلتقط ضوءاً أكثر من حسّاس ١/٢ إنش بدقّة ٢٠٠ ميجابكسل (Redmi Note 13 Pro+). الضوء هو الكاميرا، وليس البكسلات.

**القاعدة:** كاميرا ٢٠٠MP في الفئة المتوسطة لا تساوي كاميرا ٥٠MP في الفئة العليا. أبداً.

**OIS مقابل EIS:**
- **OIS (Optical Image Stabilization):** ميكانيكي، يهز العدسة لتعويض اهتزاز اليد. ضروري لتصوير الفيديو والصور في الإضاءة الضعيفة.
- **EIS (Electronic Image Stabilization):** برمجي، يقصّ من الإطار لتعويض الاهتزاز. أرخص ولكنه يفقد جودة.

أي هاتف فوق ٢٫٠٠٠ ريال يجب أن يكون فيه OIS في الكاميرا الأساسية على الأقل. لو الموديل يتباهى بـEIS فقط، اعرف أنه يخفي شيئاً.

**Night Mode الفعلي:** كل هاتف اليوم عنده "Night Mode"، لكن الجودة تتفاوت بشكل صادم. iPhone و Pixel يقدّمان أفضل Night Mode في السوق بهامش كبير. Samsung S24 جيد، لكن Xiaomi و OnePlus يميلون للمبالغة في معالجة الصورة فتطلع غير طبيعية.

**الفيديو 4K:** الفئة المتوسطة تصوّر 4K ٣٠ فريم. الفئة العليا تصوّر 4K ٦٠ فريم مع ثبات أفضل. الفرق يظهر فعلاً عند تصوير أطفال يتحركون أو سفر.

**حاسبة الكاميرا — قارن ٣ موديلات بنفس السعر:**
1. ابحث عن مراجعة DXOMARK لكل موديل (موقع مرجعي للكاميرات).
2. شاهد فيديو "camera comparison" على YouTube — يعرض الـ٣ جنباً إلى جنب.
3. اختبر شخصياً في المعرض: التقط صورة لنفس المشهد بالـ٣، وقارن على شاشة الكمبيوتر — وليس على شاشة الجوّال الصغيرة.

## البطارية والشحن: الواقع مقابل ورقة المواصفات

سعة البطارية (mAh) ليست العامل الوحيد، ولا حتى الأهم. هاتفان بسعة ٥٫٠٠٠ mAh قد يعطيك أحدهما ٨ ساعات شاشة والآخر ١٢ ساعة. الفرق في كفاءة المعالج وتحسينات النظام.

**القاعدة:** Apple يحقق أعلى عمر بطارية بأقل سعة (٣٫٢٧٤ mAh في iPhone 15 يعطي عمراً منافساً لـ٥٫٠٠٠ mAh في أندرويد). السبب: A-series كفؤ جداً في استهلاك الطاقة.

**الشحن السريع — الحقيقة:**
شحن ١٢٠W لا يعني فعلاً ٥ دقائق من صفر إلى كامل. هو يعني أن البطارية تشحن بسرعة في أول ٥٠٪، ثم تبطئ تدريجياً لحماية الخلايا. الواقع: ١٢٠W تعطيك ٠ إلى ١٠٠ في ١٨-٢٢ دقيقة. ١٢٠W هو رقم تسويقي.

**عمر البطارية بعد سنتين:** كل بطارية ليثيوم-أيون تفقد ٢٠-٢٥٪ من سعتها الأصلية بعد ٥٠٠-٨٠٠ دورة شحن كاملة (يعني سنتان من الاستخدام العادي). جهاز يعطيك ٨ ساعات شاشة جديد، سيعطيك ٦ ساعات بعد سنتين. خذ هذا في حسابك.

**متى ترقّى البطارية أم تشتري هاتف جديد؟** ترقية البطارية تكلّف ٣٠٠-٥٠٠ ريال للأندرويد (لو الموديل قطعه متوفّرة) و٥٠٠-٧٥٠ ريال لـiPhone في خدمة Apple. لو الجهاز عمره أقل من ٣ سنوات والمعالج لا يزال يكفيك، ترقية البطارية صفقة ممتازة. لو فوق ٤ سنوات، اشتر جهازاً جديداً.

**الشحن اللاسلكي:** ميزة جميلة لكنها ليست ضرورية. الشحن اللاسلكي ٥-١٥W أبطأ بكثير من السلكي، ويولّد حرارة تضر البطارية على المدى الطويل. لو ستستخدمه فقط في السيارة أو على المكتب أحياناً — جميل. لو ستعتمد عليه — لا.

## تحديثات النظام: العامر الخفي للسعر

هذه النقطة يجهلها أغلب المشترين، وهي التي تحدد فعلاً قيمة جهازك على المدى الطويل.

**سياسات الدعم الحالية:**
- **Apple:** ٦-٧ سنوات تحديثات iOS. iPhone 8 (٢٠١٧) لا يزال يحصل على تحديثات أمنية في ٢٠٢٤.
- **Samsung S/Z series:** ٧ سنوات (تحديثات نظام ٧ + أمنية ٧) — بدأت من S24.
- **Samsung A55:** ٤ سنوات نظام + ٥ سنوات أمنية.
- **Google Pixel 8/8a/8 Pro:** ٧ سنوات (من Pixel 8 إلى ما يقابله في ٢٠٣٠).
- **Xiaomi/Redmi:** ٤ سنوات تحديثات أمنية، ٣ سنوات نظام (للموديلات الجديدة).
- **OnePlus:** ٤ سنوات نظام + ٥ أمنية للموديلات الحديثة.
- **شركات صينية صغيرة (Realme، Infinix، Tecno):** سنة إلى سنتان فقط.

**الحساب الذي يكشف الحقيقة:**
- هاتف بـ٤٫٠٠٠ ريال يخدمك ٥ سنوات = **٨٠٠ ريال/سنة**.
- هاتف بـ١٫٥٠٠ ريال يخدمك سنتان = **٧٥٠ ريال/سنة**.

الفرق ٥٠ ريالاً سنوياً، لكنك تحصل على كاميرا أفضل، معالج أسرع، تصميم أفخم، وأمان أعلى طوال ٥ سنوات.

**التحديث ليس رفاهية — هو أمان:** كل تحديث أمني يسد ثغرات يمكن استغلالها لسرقة بياناتك. لو هاتفك ضاع أو سُرق، وعليه تطبيق بنكك، الفرق بين هاتف محدّث وهاتف توقفت تحديثاته قد يكون فرقاً بين حساب آمن وحساب مخترق.

نصيحة: قبل شراء أي هاتف أندرويد، ابحث في Google عن "اسم الموديل + update policy". إذا الشركة لم تلتزم بسياسة واضحة، اعتبر الجهاز بدون تحديثات بعد سنتين.

## مواصفات تُسوَّق وليست مهمة فعلاً

السوق يبيعك أرقاماً ضخمة لأن الأرقام تبيع. هذه ٦ مواصفات تُذكر في إعلانات ولا تستحق أن تدفع مقابلها:

**١. عدد cores في المعالج:** "ثُمانية أنوية!" "عشرة أنوية!" — لا يهم. ٤ أنوية كفؤة (Apple) تتفوّق على ١٠ أنوية ضعيفة. ركّز على المعالج كاسم، لا عدد أنويته.

**٢. عدد ميجابكسلات الكاميرا:** ٢٠٠MP لا تساوي شيئاً بدون حسّاس كبير وعدسة جيدة. ٥٠MP من Pixel أفضل من ٢٠٠MP من Redmi.

**٣. حجم الشاشة فوق ٦٫٧ إنش:** "أكبر = أفضل" خرافة. شاشة ٦٫٧+ تجعل الهاتف صعب الاستخدام بيد واحدة، ثقيل في الجيب، وتستهلك بطارية أكثر. ٦٫١-٦٫٣ هو الحجم المثالي للأغلبية.

**٤. وزن الجهاز كميزة "خفّة":** الهواتف الخفيفة جداً (تحت ١٧٠ جم) عادةً تأتي ببطارية أصغر. الوزن المتوازن (١٨٠-٢٠٠ جم) عادةً يعني بطارية محترمة وبناء صلب.

**٥. dual SIM مقابل eSIM:** للسعودية تحديداً، eSIM متاح في STC وموبايلي وزين، ولكنه لا يُغني عن SIM فيزيائي إذا تسافر كثيراً لدول لا تدعم eSIM. الجواب: ميزة dual SIM (فيزيائي + eSIM) معاً مفيدة، لكن لا تدفع ٥٠٠ ريال إضافياً مقابلها.

**٦. "Pro" في اسم الموديل:** Pro لا تعني فعلياً جودة احترافية. كل شركة تستخدمها بمعنى مختلف. iPhone Pro فعلياً أعلى من iPhone العادي بفارق كبير. لكن "Pro" في Redmi أو Realme قد تعني فقط شاشة أكبر بهامش. اقرأ الفرق التفصيلي، لا الاسم.

**٧. إطار شاشة صغير جداً (Bezel-less):** التصاميم بدون إطار أو بإطار ٢ ملم تكسر بسهولة عند سقوط الجهاز. إطار ٤-٥ ملم أكثر متانة، والفرق البصري لا يلاحظ في الاستخدام اليومي.

## كيف تفحص الهاتف عند الاستلام — قائمة ١٠ خطوات

سواء اشتريت من نون أو أمازون السعودية أو معرض، افحص الجهاز خلال أول ٢٤ ساعة. كل المواقع الكبرى تسمح بالإرجاع خلال ٧-١٤ يوماً لو الجهاز معيب.

**١. افحص الكرتون قبل فتحه:** التأكد من السيريل (Serial) على الكرتون، الباركود، وأن الختم سليم. تطابق الـIMEI على الكرتون مع الجهاز ضروري.

**٢. تحقق من الـIMEI:** اطلب `*#06#` على لوحة الأرقام. سيظهر رقم IMEI. قارنه مع المطبوع على الكرتون والمطبوع تحت البطارية (في إعدادات الجهاز). أي اختلاف يعني الجهاز مفتوح/مبدّل.

**٣. اختبر الشاشة:** افتح يوتيوب وشغّل فيديو شاشة سوداء كاملة. ابحث عن نقاط ميتة (Dead Pixels) — نقاط لا تتغير لونها. ثم شاشة بيضاء — ابحث عن بقع أو تباين غير طبيعي.

**٤. اختبر اللمس والحساسية:** ارسم خطوطاً متعرّجة في تطبيق الرسام أو Notes. تأكد أن كل سنتيمتر من الشاشة يستجيب. اختبر حواف الشاشة تحديداً — هي المنطقة التي يحدث فيها أكبر فشل لمس.

**٥. اختبر الكاميرات الثلاث (أو الأربع):** التقط صورة من كل كاميرا (Wide، Ultra-wide، Telephoto). اختبرها في **إضاءة بيت طبيعية** — وليس في إضاءة المعرض القوية. شغّل فيديو 4K لمدة دقيقة كاملة وتأكد من الثبات.

**٦. اختبر الجي-بي-إس، الواي-فاي، والبلوتوث:** افتح Google Maps في الشارع وتأكد من دقّة الموقع خلال ٣٠ ثانية. اتصل بشبكة واي-فاي معروفة. اربط الجهاز بإيربودز أو سيارة عبر بلوتوث.

**٧. اختبر السمّاعات والميكروفون:** شغّل فيديو بصوت عالٍ، استمع لتشويش. سجّل ملاحظة صوتية بالميكروفون وارجع اسمعها — يجب أن تكون واضحة بلا همهمة.

**٨. اختبر الـStress للمعالج:** نزّل تطبيق AnTuTu أو Geekbench. شغّل اختبار الـ stress test لمدة ١٥ دقيقة. الجهاز يجب ألا يتجاوز ٤٥ درجة مئوية على الظهر، وألا يخنق الأداء أكثر من ٣٠٪.

**٩. قِس عمر البطارية الفعلي:** اشحن الجهاز ١٠٠٪، ثم استخدمه ١٠ دقائق بكثافة (لعبة، فيديو، تصفّح). إذا انخفضت البطارية أكثر من ٤-٥٪، فهذا مؤشر على بطارية ضعيفة أو معالج غير كفؤ.

**١٠. تحقق من الشحن السريع:** أوصل الشاحن الأصلي (المرفق أو المنفصل لـiPhone). يجب أن ترى تحت زر الشحن "شحن سريع" أو "Fast Charging". لو ما ظهر، الكابل أو الشاحن غير متوافق.

**علامات حمراء تستوجب الإرجاع فوراً:**
- خدوش على الشاشة قبل إزالة الفيلم الواقي.
- جهاز يأتي مشحوناً فوق ٥٠٪ (يعني تم تشغيله ربما من قبل).
- لغة افتراضية ليست العربية أو الإنجليزية (قد يكون من سوق آخر).
- ملاحقة الشاحن أو الكابل بعلامات استخدام.

## متى تشتري — التوقيت يوفّر ١٥-٢٥٪

التوقيت يفرق بقدر ما يفرق الموديل. الانتظار ٣-٤ أشهر قد يوفّر عليك ١٫٠٠٠ ريال على نفس الجهاز.

**جدول الإطلاقات السنوي:**
- **سبتمبر:** Apple يطلق iPhone الجديد. هذا أفضل وقت لشراء **iPhone موديل سنة سابقة** — يخفض سعره ١٥-٢٠٪ فوراً.
- **يناير-فبراير:** Samsung يطلق Galaxy S الجديد. موديل S السابق يخفض ٢٠-٢٥٪.
- **مايو-يونيو:** Samsung S FE وموديلات Pixel A تطلق.
- **أكتوبر-نوفمبر:** Pixel الجديد، OnePlus الجديد، Xiaomi الجديد.

**أحداث التخفيضات الكبرى في السعودية:**
- **يلّو فرايدي في نون (نوفمبر):** أكبر تخفيضات السنة على الإلكترونيات. هواتف منتصف الفئة قد تخفض ٢٠-٣٥٪.
- **وايت فرايدي / بلاك فرايدي (نوفمبر):** كل المنصات تشارك.
- **Eid sales (الفطر والأضحى):** تخفيضات أقل من بلاك فرايدي لكن جيدة.
- **سنغل داي ١١/١١:** أمازون السعودية و Temu يشاركان.
- **بداية الموسم الدراسي (أغسطس):** تخفيضات على الأجهزة الموجهة للطلاب.

**متى التوقيت سيء:**
- **أول ٣٠ يوماً من إطلاق موديل جديد:** السعر في ذروته، ومن المعتاد ظهور bugs في الإصدار الأول من النظام (Firmware initial). انتظر التحديث الأول.
- **رمضان مباشرة (التخفيضات تكون مدروسة لكن مزعومة):** قارن الأسعار قبل رمضان بأسبوعين.
- **بداية السنة (يناير):** المخزون قديم، التخفيضات قليلة.

**نصيحة عملية:** أضف الموديل الذي تريده إلى قائمة الرغبات في نون وأمازون السعودية، وفعّل تنبيهات السعر. سترى متى ينخفض فعلياً، وليس متى تدّعي المنصة "تخفيضاً".

## الأسئلة الشائعة (FAQ)

### السؤال: هل آيفون مستعمل أفضل من أندرويد جديد بنفس السعر؟

في الغالب نعم، خصوصاً إذا كان الآيفون المستعمل من جيل آخر سنتين (مثلاً iPhone 13 بسعر ٢٫٢٠٠ ريال) مقابل أندرويد جديد بنفس السعر. الآيفون سيحصل على تحديثات ٣-٤ سنوات إضافية، بينما الأندرويد بنفس السعر سيحصل على تحديثات سنة-سنتين فقط. تأكد فقط من فحص البطارية (إعدادات > البطارية > حالة البطارية، يجب أن تكون فوق ٨٥٪).

### السؤال: متى يكون الهاتف الصيني خياراً ذكياً ومتى مخاطرة؟

ذكي لو من العلامات الكبيرة (Xiaomi، OnePlus، Honor) وموديل أُطلق رسمياً في السعودية. مخاطرة لو من علامات صغيرة (Tecno، Infinix الفئة الدنيا) أو لو الموديل لم يصدر رسمياً في الخليج. السبب: التحديثات، خدمة ما بعد البيع، وضمان الوكيل.

### السؤال: هل أحتاج فعلاً شاشة AMOLED؟ أم LCD يكفي؟

لو تستخدم الهاتف ساعات طويلة يومياً، AMOLED يفرق فعلاً — ألوان أعمق، أسود حقيقي، استهلاك بطارية أقل في الوضع الداكن. لو استخدامك خفيف، LCD يكفي تماماً ويوفّر عليك ٣٠٠-٥٠٠ ريال.

### السؤال: ما الفرق بين eSIM و SIM فيزيائي للاستخدام في السعودية؟

eSIM مدعوم من STC، موبايلي، وزين. الفرق العملي: eSIM لا يمكن تبديله إلى جهاز آخر بسحبه ولصقه — تحتاج إجراءً من المشغّل. لو تبدّل أجهزة كثيراً، SIM فيزيائي أسهل. لو تسافر كثيراً، dual SIM (فيزيائي + eSIM) يعطيك المرونة.

### السؤال: أيهما أفضل: شحن سريع ١٢٠W أم بطارية بسعة أكبر؟

البطارية الأكبر أفضل في ٩٠٪ من الحالات. الشحن السريع ١٢٠W يولّد حرارة تختصر عمر البطارية على المدى الطويل. لو روتينك يسمح بشحن ليلي عادي، اختر بطارية أكبر وشحن ٤٥-٦٧W.

### السؤال: هل ضمان الوكيل يستحق الفرق في السعر؟

نعم في ٩٥٪ من الحالات. الفرق بين سعر الوكيل وسعر السوق الموازي (المستورد) عادةً ٣٠٠-٧٠٠ ريال. هذا المبلغ هو ثمن خدمة الإصلاح، استبدال الجهاز عند العيب، وضمان توفّر قطع الغيار. وكلاء Apple و Samsung في السعودية معروفون بجودة خدمة ممتازة.

### السؤال: متى أرقّى هاتفي؟ هل بطء التطبيقات هو الإشارة؟

بطء التطبيقات قد يكون بسبب تحديث نظام جديد على جهاز قديم — جرّب مسح ذاكرة التخزين المؤقت أولاً (Settings > Storage > Cached Data). الإشارات الحقيقية: البطارية لا تكفي نص يوم، الجهاز لا يستلم تحديثات أمنية لـ٦ أشهر، الشاشة بها مشاكل لمس متكررة. لو ٢ من هذه الـ٣ يحدثان، حان وقت الترقية.

### السؤال: هل آمن شراء هاتف من الأسواق الموازية بسعر أقل؟

قانونياً مسموح، لكن المخاطر: لا ضمان وكيل، الشاحن قد لا يكون الأصلي، بعض الموديلات تأتي بنظام تشغيل بلغة أجنبية يصعب تغييرها، ولن تستفيد من برامج الاستبدال (Trade-in) لاحقاً. اختر فقط لو الفرق فوق ١٫٠٠٠ ريال ومتأكد من البائع.

### السؤال: كيف أحمي بياناتي عند بيع هاتفي القديم؟

١) سجّل خروج من كل الحسابات (Apple ID / Google). ٢) عطّل Find My iPhone / Find My Device. ٣) اعمل Factory Reset (إعدادات > النظام > إعادة ضبط). ٤) لـiPhone خاصة: امسح الجهاز من iCloud.com حتى لو الجهاز عند المشتري. ٥) سحب الـSIM وكرت الميموري.

### السؤال: الـRefurbished من Apple مقابل الجديد — يستحق التوفير؟

نعم. Apple Refurbished يأتي ببطارية جديدة، كرتون جديد، ضمان كامل سنة، وسعر أقل ١٥-٢٠٪ من الجديد. الفرق الوحيد: الهيكل مستعمل (لكن مفحوص). لو متاح في السعودية وموديل يناسبك، اشتر بثقة.

### السؤال: هل DLSS أو AI-photography حقيقة فرق فعلي أم تسويق؟

فرق فعلي ولكنه مبالغ في تسويقه. AI photography (Google Pixel و Apple) يحسّن الصور في الظروف الصعبة (ليل، إضاءة معاكسة) بشكل ملحوظ. لكن "AI" في إعلانات الشركات الصينية الصغيرة عادةً مجرد فلتر آلي لتشبيع الألوان — ليس ذكاءً اصطناعياً حقيقياً.

### السؤال: أيهما أهم لي: تخزين ٢٥٦ جيجا داخلي أم ١٢٨ جيجا + كرت ميموري؟

التخزين الداخلي أسرع بـ٤-١٠ مرات من كرت الميموري. لو تصوّر فيديوهات 4K أو تلعب ألعاباً ثقيلة، اختر ٢٥٦ جيجا داخلي. لو استخدامك خفيف ومجرد تخزين صور وفيديوهات قصيرة، ١٢٨ + كرت يكفي. مهم: iPhone و أغلب فلاجشب الأندرويد لا تدعم كرت ميموري أصلاً.

