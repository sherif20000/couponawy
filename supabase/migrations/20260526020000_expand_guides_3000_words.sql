**٦. ميزانية مرنة أم سقف صارم؟** لو السقف صارم، التزم به ولا تسمح للبائع برفعك ٥٠٠ ريال "بس". لو مرنة، تذكّر أن الفرق بين ٤٫٠٠٠ و٥٫٠٠٠ ريال قد لا يكون مرئياً يومياً — السؤال هل تحتاج كاميرا التيليفوتو ٥x فعلاً.

**٧. تستخدم نظام Apple بالفعل؟** لو عندك آيباد، ماك، إيربودز — التحوّل لأندرويد سيكلّفك راحة كثيرة (AirDrop، Handoff، iMessage، Find My). البقاء في النظام يستحق الفرق. والعكس صحيح لو نظامك حول جوجل و Samsung.

**٨. مهتم بالخصوصية على مستوى النظام؟** Apple وGoogle Pixel يتقدّمان في خيارات الخصوصية وحذف الإعلانات. شركات صينية معيّنة تشحن أنظمة بإعلانات داخل النظام نفسه — يمكن تعطيلها لكنها تعود مع التحديثات.

أجب على الـ٨ أسئلة كتابةً، ثم اقرأ الميزانيات الأربع وأنت تعرف نفسك.

## الميزانيات الأربع — تحليل عميق

### الفئة الأولى: تحت ١٫٥٠٠ ريال

**الفئة المثالية:** المستخدم الخفيف، الطالب، الوالد/الوالدة الذي يحتاج جهازاً للاتصال والواتساب والكاميرا العائلية. أيضاً جهاز ثانوي للسفر أو للولد المراهق الذي قد يكسر أو يفقد الجهاز.

**موديلات محدّدة:** Redmi Note 14، Samsung Galaxy A16، Realme C75، Infinix Note 40. هذه أجهزة تشتغل، تصور صور معقولة في النهار، وتمسك يومين بطارية للمستخدم الخفيف.

**نقاط القوة:** السعر، الشاشة الكبيرة، البطارية الضخمة (٥٫٠٠٠ mAh عادةً)، توفّر القطع البديلة في السوق المحلي بأسعار رخيصة.

**نقاط الضعف:** المعالج خانق تحت الضغط، الكاميرا تنهار في الإضاءة الضعيفة، تحديثات النظام محدودة (سنتان كحد أقصى)، البلاستيك يبدو رخيصاً، وأحياناً يأتي مع إعلانات داخل النظام.

**العمر المتوقع قبل الإحباط:** ١٨-٢٤ شهراً. بعد ذلك التطبيقات الحديثة ستبدأ تثقل عليه، والبطارية ستفقد ٢٠٪ من سعتها الأصلية.

استخدم كوبون قبل الشراء — [تصفّح كوبونات الإلكترونيات](/categories/electronics) قد توفّر ١٠٠-٢٠٠ ريال إضافية على هذه الفئة.

### الفئة الثانية: ١٫٥٠٠-٣٫٠٠٠ ريال

**الفئة المثالية:** الموظف العادي، المستخدم المتوسط الذي يصوّر ويستخدم سوشيال ميديا ويلعب ألعاباً خفيفة. هي الفئة الذهبية من حيث القيمة مقابل السعر، وهي التي يقع فيها أغلب المشترين الواعين في السعودية.

**موديلات محدّدة:** Samsung Galaxy A35/A55، Pixel 8a، Nothing Phone 2a، Xiaomi 13T، Redmi Note 14 Pro Plus، Realme GT Neo 6. الـPixel 8a تحديداً صفقة عظيمة في هذه الفئة لأنها تحمل معالج Tensor G3 (نفس الفلاجشب) وكاميرا تنافس الفئة الأعلى منها.

**نقاط القوة:** كاميرا جيدة في معظم الظروف، معالج كافٍ لأي شيء غير الألعاب الثقيلة جداً، تحديثات ٤-٧ سنوات (بالذات Pixel و Samsung A55)، تصميم زجاج/معدن، شحن سريع معقول.

**نقاط الضعف:** الكاميرا التيليفوتو غالباً مفقودة (تعتمد على zoom رقمي)، الفيديو 4K أحياناً يهتز، اللعب الثقيل (PUBG على Ultra) يسخّن الجهاز.

**العمر المتوقع قبل الإحباط:** ٣-٤ سنوات إذا اخترت موديلاً بدعم تحديثات طويل (Pixel 8a، Samsung A55). سنتان لو اخترت Xiaomi أو Realme.

### الفئة الثالثة: ٣٫٠٠٠-٥٫٠٠٠ ريال

**الفئة المثالية:** المستخدم الذي يعتمد على هاتفه في العمل (تصوير محتوى، إيميلات، اجتماعات Zoom)، أو الذي يبدّل كل ٣-٤ سنوات ويريد جهازاً يستحمل المدة. أيضاً مَن يصوّر أطفاله بكثرة ويريد كاميرا تنجز في كل الظروف.

**موديلات محدّدة:** iPhone 15، Samsung Galaxy S24 FE، Xiaomi 14، Pixel 8، OnePlus 12، Samsung S23 (موديل سنة سابقة بسعر مخفّض). الـiPhone 15 هنا صفقة ممتازة لأن Apple ستدعمه ٦-٧ سنوات بتحديثات.

**نقاط القوة:** كاميرا فلاجشب تقريباً، معالج لا يخنق تحت الضغط، شاشة AMOLED ١٢٠Hz، تصميم premium، شحن لاسلكي، IP68 (مقاومة الماء)، NFC ومدفوعات Apple Pay/Google Pay.

**نقاط الضعف:** غير ضرورية لمستخدم خفيف — هي قفزة سعر كبيرة عن الفئة الثانية مقابل تحسينات يصعب رؤيتها يومياً. أيضاً قطع الغيار مكلفة (شاشة iPhone 15 الأصلية تتجاوز ١٫٢٠٠ ريال).

**العمر المتوقع قبل الإحباط:** ٤-٦ سنوات. iPhone 15 تحديداً يتوقع أن يصل لعام ٢٠٣٠ بتحديثات.

### الفئة الرابعة: فوق ٥٫٠٠٠ ريال

**الفئة المثالية:** صانع المحتوى، المصوّر الجاد، رجل الأعمال الذي يحتاج كل ميزة، أو من يريد ببساطة أفضل ما تنتجه الشركات. أيضاً مَن يستخدم Apple Pencil على آيباد ويريد التكامل الكامل مع iPhone Pro.

**موديلات محدّدة:** iPhone 15 Pro Max / iPhone 16 Pro Max، Samsung Galaxy S24 Ultra، Pixel 8 Pro، Xiaomi 14 Ultra، OnePlus 12 (في الحد الأدنى من هذه الفئة).

**نقاط القوة:** كاميرا تيليفوتو ٥x حقيقية بصرياً، فيديو 4K ٦٠ فريم ثابت، شاشة LTPO ١٢٠Hz متكيّفة، معالج لا يخنق حتى في ساعة لعب متواصلة، تخزين يصل ١ تيرابايت، Titanium frame في Apple/Samsung.

**نقاط الضعف:** السعر — الفرق بين Pro Max وiPhone 15 العادي قد يصل ٢٫٠٠٠ ريال مقابل ميزات قد لا تستخدم نصفها. الوزن ثقيل (٢٢١ جراماً للـUltra). الكاميرات بارزة جداً ويصعب وضع الجهاز على طاولة دون كفر.

**العمر المتوقع قبل الإحباط:** ٥-٧ سنوات. هذه الأجهزة تكون أول من يحصل على التحديثات وآخر من يفقد الدعم.

[تصفّح كوبونات الإلكترونيات](/categories/electronics) قبل شراء أي جهاز من هذه الفئة — التوفير قد يكون بمئات الريالات.

## المعالج: السؤال التقني الأهم

المعالج هو القلب. كل ما يأتي بعده — الكاميرا، البطارية، التطبيقات — يعتمد عليه. لكن السوق مليء بأسماء معقدة بشكل مقصود لتربكك.

**العائلات الرئيسية الأربع:**
- **Apple A-series** (A15، A16، A17 Pro، A18 Pro): الأقوى والأكفأ في العالم حالياً. تخص iPhone فقط.
- **Qualcomm Snapdragon** (8 Gen 3، 8s Gen 3، 7 Gen 3): العائلة المسيطرة على فلاجشب الأندرويد.
- **MediaTek Dimensity** (9300، 8300، 7200): قفزت في السنتين الماضيتين وأصبحت تنافس Snapdragon فعلياً في الفئة المتوسطة والعليا.
- **Google Tensor** (G3، G4): مخصص لـPixel، يركّز على الذكاء الاصطناعي أكثر من الأداء الخام.

**الجيل أهم من الفئة.** هذه نقطة يفوّتها كثيرون. Snapdragon 7 Gen 3 (٢٠٢٣) يتفوق على Snapdragon 8 Gen 1 (٢٠٢١) في كفاءة البطارية والحرارة، رغم أن الثاني "أعلى فئة". القاعدة: جيل جديد متوسط > جيل قديم عالي.

**كيف تقرأ نتائج البنشمارك:** Antutu و GeekBench هما المعياران. لا تحفظ الأرقام، احفظ التصنيفات:

