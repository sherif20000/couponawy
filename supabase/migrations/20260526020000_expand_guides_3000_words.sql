### ما تفحصه في أول ٢٤ ساعة من الاستلام

موقفك القانوني والتفاوضي أقوى ما يكون في أول ٢٤ ساعة. **افحص فوراً**:

1. **افتح الصندوق أمام المندوب لو أمكن**، خصوصاً للطلبات بقيمة فوق ٥٠٠ ريال.
2. **صوّر فيديو "Unboxing"** كاملاً قبل فتح الأكياس الداخلية. هذا الفيديو هو دليلك القانوني لو وصل المنتج معيباً أو ناقصاً.
3. **اطبع صوراً للعيوب الواضحة**: خياطة منفلتة، بقعة، لون مختلف عن الصورة، تاج مكسور أو غير موجود.
4. **جرّب المقاس فوراً**، حتى لو لن تلبسه إلا بعد أسبوع. مدّة الإرجاع تبدأ من تاريخ الاستلام، لا من تاريخ التجربة.
5. **احفظ التغليف الأصلي والفاتورة والبطاقات** لمدة كاملة سياسة الإرجاع. كثير من المتاجر ترفض الإرجاع لو فُقدت البطاقة الأصلية.
6. **سجّل رقم الطلب وحالة الإرجاع في مكان واحد** (Google Sheet أو ملاحظة في الهاتف) خصوصاً لو تتسوّق من أكثر من متجر شهرياً.

### الفرق بين "إرجاع" و"استبدال" و"استرداد"

- **استبدال (Exchange)**: نفس المنتج بمقاس أو لون مختلف. أسرع عادة، الشحن في الاتجاهين مجاني في معظم المتاجر الكبرى.
- **إرجاع مع استرداد (Refund)**: تستعيد المبلغ. مدّة الاسترداد ٧-١٤ يوم عمل بعد استلام المتجر للمنتج. على البطاقة الائتمانية الاسترداد أبطأ من المحفظة الإلكترونية للمتجر (نقاط نمشي، رصيد شي إن).
- **رصيد للمتجر (Store Credit)**: المتجر يرجع الفلوس كرصيد داخلي. ارفض هذا الخيار إلا لو كنت متسوّقاً منتظماً من نفس المتجر، لأن الرصيد ينتهي عادة بعد ٦-١٢ شهر.

## ٤. استراتيجية "اطلب مقاسين" — متى تستحق ومتى لا

عند الشكّ بين مقاسين، الحل: اطلب الاثنين. ترجع واحداً مجاناً (لو المتجر يدعم الإرجاع المجاني)، تكلفتك الفعلية صفر، وفّرت رحلة ثانية وانتظار أسبوع آخر.

**الحساب المالي**: تيشيرت بـ١٢٠ ريال، تطلب M و L = ٢٤٠ ريال تخصم من البطاقة. خلال ٧-١٠ أيام بعد الإرجاع، ١٢٠ ريال تعود لك = صفر تكلفة فعلية. لو لم تستخدم الاستراتيجية وطلبت M فقط ولم يناسبك، أنت الآن: خسرت أسبوع، شحنت إرجاع، أعدت الطلب بمقاس L، شحن جديد، أسبوع آخر. الفرق ١٤ يوم.

**متى تستحق الاستراتيجية**:

- منتجات بـ١٠٠-٥٠٠ ريال مع إرجاع مجاني (لا تربط فلوسك في ١٠٠٠ ريال لشراء بنطلونين).
- ملابس عملية تومية: قمصان، تيشيرتات، بناطيل عادية، فساتين بسيطة.
- متاجر بسياسة إرجاع سهلة ([نمشي](/stores/namshi)، [نون](/stores/noon)، Mango).
- عندما الفرق بين مقاسين ضئيل في جدول المتجر (مثلاً صدرك ٩٢ سم وعلى الحدّ بين S وM).

**متى لا تستحق الاستراتيجية**:

- **عبايات وفساتين سهرة**: تحتاج تجربة في مرآة كبيرة مع إضاءة طبيعية، ومع كعب الحذاء الذي ستلبسه. المرآة الصغيرة في غرفة النوم لا تكفي.
- **منتجات "Final Sale" أو "بيع نهائي"**: غير قابلة للإرجاع أصلاً، أنت تخاطر بمئات الريالات.
- **الحاجة الفورية**: لو المناسبة بعد ٤٨ ساعة، طلب مقاسين قد لا يصل في الوقت، والإرجاع لاحقاً لا يفيدك.
- **ملابس من متاجر تطبّق رسوم على الإرجاع** بعد المرّة الأولى (شي إن، Bershka عند الإرجاع المنزلي).

**بديل أحدث وأرخص**: تطبيقات "AR Try-On" بدأت تظهر في متاجر كبيرة (Sephora لمستحضرات التجميل، ASOS لبعض الملابس، Zara في بعض الفروع). لو المتجر يدعم تجربة افتراضية، استخدمها قبل اللجوء لاستراتيجية المقاسين. لا تكفي للقماش لكنها تكفي لاختيار اللون والقصّة العامة.

## ٥. أين تجد الكوبونات الفعّالة وكيف تستخدمها بذكاء

الكوبون الجيد يقطع ١٠-٤٠٪ من السعر، لكن استخدامه الخاطئ قد يلغي خصماً موسمياً أكبر. القاعدة الذهبية: **احسب قبل أن تطبّق**.

**كيف تجمع كوبون مع تخفيض موسمي**: بعض المتاجر تسمح، بعضها لا. اختبر بسرعة:

1. ضع المنتج في السلّة.
2. لاحظ السعر بعد التخفيض الموسمي الظاهر.
3. طبّق الكوبون.
4. لو السعر نقص أكثر، الكوبون قابل للجمع. لو ظهرت رسالة "غير ساري على المنتجات المخفّضة"، اختر: الخصم الموسمي وحده، أو ارفع المنتج المخفّض وأضف منتجاً بسعر كامل لتستفيد من الكوبون.

**جدول الكوبونات الشهرية المعتادة لأهم المتاجر**:

| المتجر | الكوبون الشهري المعتاد | التخفيض الموسمي الأكبر | هل تستحقّ الجمع؟ |
|---|---|---|---|
| [نمشي](/stores/namshi) | ١٠-١٥٪ على المتسوّق الجديد | Black Friday حتى ٧٠٪ | الكوبون لا يجمع مع تخفيض فوق ٥٠٪ |
| [شي إن](/stores/shein) | ١٠-٢٠٪ تقريباً شهرياً | Flash Sale يومي | نعم، أحياناً يجمع |
| [نون](/stores/noon) | كوبونات بنكية (الراجحي، الأهلي) | Yellow Friday | بنكي + موسمي = ممتاز |
| Mango | ١٥٪ على المتسوّق الجديد | End of Season | لا يجمع |
| [أمازون السعودية](/stores/amazon-sa) | كوبونات منتج محدّدة | Prime Day | نعم، يجمع |

**أين تجد كوبونات موثوقة**: لا تتعب نفسك بالبحث في عشرات المواقع المشكوك بها. المنصة المتخصّصة (مثل صفحة [كوبونات الموضة](/categories/fashion) في هذا الموقع) تجمع الكوبونات الفعّالة وتتحقّق منها يومياً. ركّز على متجر واحد رئيسي لكل فئة (نمشي للموضة، نون للأطفال، أمازون للأحذية الرياضية) لتبني علاقة "متسوّق دائم" وتستفيد من برامج الولاء.

**الكوبونات السرّية**: عند ترك السلّة بدون شراء لـ٢٤ ساعة، كثير من المتاجر ترسل بريداً إلكترونياً بكوبون "ارجع لإكمال طلبك" بقيمة ١٠-٢٠٪. اختبر هذا، خصوصاً مع زارا و[شي إن](/stores/shein).

## ٦. التوقيت الذكي للشراء — تقويم سنوي للموضة

شراء الملابس في الوقت الخطأ يكلّفك ٣٠-٥٠٪ زيادة. اتبع هذا التقويم لتشتري كل قطعة بأرخص سعرها:

**يناير**: تنزيلات نهاية موسم الشتاء (٤٠-٦٠٪). اشترِ: معاطف، جواكت ثقيلة، أحذية شتوية. تجنّب: ملابس الموسم الجديد (ربيع/صيف) التي ستظهر بأسعار افتتاحية في فبراير.

**فبراير**: ظهور مجموعة الربيع بأسعار كاملة. تجنّب الشراء إلا للضرورة. اشترِ: قطع داخلية وأساسيات لا علاقة لها بالموسم.

**مارس-أبريل**: ملابس صيفية بأسعار افتتاحية، عادة مع كوبونات ١٥-٢٠٪ للتسوّق المبكّر. اشترِ: تيشيرتات، قمصان قطنية، فساتين خفيفة. تجنّب: ملابس شتوية (انتظر العام القادم).

**رمضان (يتغيّر تاريخه)**: عروض رمضانية مكثّفة على العبايات، أزياء الأطفال، ملابس العيد. اشترِ: عبايات، ثياب رجالية رسمية، ملابس عيد. تجنّب: تركيبات الموضة المعتادة (تباع بأسعار موسمية عادية).

**يونيو-يوليو (Mid-Year Sale)**: ٣٠-٥٠٪ خصم على معظم القطع. أفضل وقت لشراء قطع صيفية بكميات. اشترِ: شورتات، صنادل، بدلات سباحة، حقائب صيف. تجنّب: قطع موسم الشتاء القادم (سعرها سيكون أرخص في يناير ٢٠٢٧).

**أغسطس**: نهاية الصيف، تنزيلات حتى ٥٠-٦٠٪ على ما تبقّى. اشترِ: تيشيرتات لاستخدام العام القادم، صنادل، أحذية رياضية. تجنّب: ملابس مدرسية بكامل سعرها (موجة "Back to School" أرخص في سبتمبر).

**سبتمبر**: مجموعات الخريف بأسعار كاملة + حملات "Back to School" للأطفال. اشترِ: قرطاسية، حقائب مدرسية، أحذية أطفال. تجنّب: جواكت ثقيلة (تنزل في يناير).

**أكتوبر**: قبل الذروة، أسعار عادية. وقت تخطيط، اصنع قائمة "Black Friday Wishlist" واحفظ المنتجات في المفضّلة.

**نوفمبر — الذروة**: Black Friday + Yellow Friday + White Friday (يتغيّر الاسم حسب المتجر). أكبر تخفيضات السنة، ٥٠-٧٠٪. اشترِ: كل ما خطّطت له. تجنّب: الشراء العاطفي ("ارخص نشتري")، الالتزام بالقائمة.

**ديسمبر**: تخفيضات نهاية السنة على المتبقّيات من Black Friday. مقاسات شائعة (M, L) قد تكون نفدت. اشترِ: لو وجدت مقاسك. تجنّب: التوقّع بأن كل شيء سيكون متوفّراً.

**القاعدة الذهبية**: لا تشترِ قطعة قبل موسم استخدامها بأكثر من ٣ أشهر، إلا في تخفيض كبير (٤٠٪+). تذوقك قد يتغيّر، أو وزنك، أو الموضة.

## ٧. حذار من ٨ فخاخ شائعة في التسوّق أونلاين

١. **"المؤثّر يلبس مقاساً أصغر"**: المؤثّرون على إنستغرام وتيك توك كثيراً ما يطلبون مقاساً أصغر برقم ليبدو الفستان "مشدوداً وأنيقاً" في الصورة. لا تستنتج مقاسك من صورتهم. ابحث عن تقييم بصور حقيقية لشخص بطولك ووزنك.

٢. **الصور المنقوحة**: ألوان مشبعة بفلتر، خياطة "تختفي"، طيّات قماش "تنبسط" بالفوتوشوب. للتأكّد، استخدم Google Image Search Reverse: حمّل صورة المنتج، ابحث بها، قارن مع نسخ أخرى لنفس المنتج من بائعين مختلفين.

٣. **منتج "تيمو" مطابق لصورة معروفة**: لو رأيت صورة لفستان من علامة شهيرة معروضاً على Temu بربع السعر، ٩٠٪ من المرات الصورة مسروقة والمنتج الفعلي مختلف. اقرأ تقييمات Temu بصور المشترين، لا صور البائع.

٤. **صور البائع الأصلي مقابل المسروقة**: على [نون](/stores/noon) و[أمازون السعودية](/stores/amazon-sa)، نفس المنتج قد يباع من عدّة بائعين. بعضهم يستخدم صور البائع الأصلي للتسويق ثم يرسل منتجاً تقليدياً. اطلب من البائع برسالة قبل الشراء "هل المنتج مطابق للصور الموجودة؟" — الرد المتأخّر أو غير الواضح إشارة سيئة.

٥. **فخّ "شحن مجاني فوق ٢٠٠ ريال"**: مصمّم نفسياً لتدفعك لشراء منتج إضافي بـ٤٠ ريالاً لتجنّب رسوم شحن ١٥ ريالاً. النتيجة: أنفقت ٢٥ ريالاً زائدة. الحل: لو سلّتك بـ١٨٠ ريالاً واحتجت ٢٠ ريالاً للوصول للحدّ، احسب: هل الـ٢٠ ريال تستحق تجنّب ١٥ ريال شحن؟ غالباً لا.

٦. **"٤ قطع متبقّية فقط"**: تكتيك ضغط نفسي مألوف. أحياناً صحيح (للمقاسات الشائعة)، لكنه غالباً متجدّد آلياً ليبقى يظهر دائماً. لا تتسرّع. أعد فتح الصفحة بعد ساعة، إذا لا يزال "٤ متبقّية" فأنت تعرف الجواب.

٧. **"العدّاد التنازلي للخصم"**: "الخصم ينتهي بعد ٢٣ دقيقة!". الواقع: يبدأ عدّاداً جديداً عند تحديث الصفحة. الخصم نفسه عادة متوفّر طوال الأسبوع.

٨. **خداع "السعر الأصلي" المضخّم**: المتجر يضع "السعر الأصلي ٤٠٠ ريال، الآن ١٢٠ ريال". في الواقع المنتج لم يبع أبداً بـ٤٠٠، بل بـ١٥٠ في الأشهر السابقة. استخدم أدوات تتبّع الأسعار (CamelCamelCamel لأمازون، Keepa)، أو خذ لقطة شاشة لسعر المنتج أسبوعياً قبل التخفيضات الكبرى.

