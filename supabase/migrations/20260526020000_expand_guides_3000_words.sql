## أخطاء يقع فيها المتسوّقون الجدد

كل واحد من هالأخطاء يكلّفك فلوس بدون ما تحس. تجنّبها يوفّر عليك مئات الريالات سنوياً:

- **شراء من بائع ثالث بدون قراءة تقييماته**: كثير من حالات الغش تجي من بائعين تقييمهم أقل من ٩٠٪ أو عدد تقييماتهم قليل. قاعدة عامة: لا تشتري من بائع تقييمه أقل من ٤.٢ نجوم أو عنده أقل من ١٠٠ تقييم، حتى لو السعر أرخص ٢٠٪.
- **افتراض أن السعر النهائي = السعر المعروض**: السعر اللي تشوفه ما يشمل أحياناً الشحن، الضريبة (١٥٪)، رسوم الدفع عند الاستلام (١٠–٢٠ ريال). دائماً اطلع على صفحة "ملخص الطلب" قبل تأكيد الدفع.
- **تخزين السلة أكثر من ٢٤ ساعة**: الأسعار في المنصّتين تتغيّر ديناميكياً. منتج بسلتك بسعر ٤٥٠ ريال اليوم، ممكن يطلع بكرا ٤٧٥ بدون سابق إنذار. إذا قرّرت تشتري، اشترِ.
- **نسيان تفعيل الكوبون قبل الدفع**: كثير من الناس يشوفون كوبون في صفحة المنتج، يضيفون للسلة، وينسون يضغطون "تطبيق". قبل الضغط على "ادفع"، تحقّق من سطر "الخصم" في ملخص الطلب.
- **عدم مقارنة السعر مع منصّة ثانية**: خمس دقائق مقارنة بين أمازون ونون توفّر أحياناً ٥٠–٣٠٠ ريال. اجعلها عادة لكل عملية شراء فوق ٢٠٠ ريال.
- **الانخداع بالخصم بدل القيمة**: "خصم ٧٠٪" على منتج ما تحتاجه ما هو توفير، هو إنفاق. السؤال الصح: "كم أوفّر مقابل سعر السوق الفعلي لمنتج فعلاً أحتاجه؟"
- **تجاهل سياسة الإرجاع قبل الشراء**: بعض المنتجات (ملابس داخلية، مستحضرات تجميل مفتوحة، طعام) ما يقبلون إرجاعها. اقرأ سياسة الإرجاع قبل الدفع، مو بعدها.
- **شراء أجهزة كهربائية بدون فحص الضمان**: ضمان الوكيل المحلّي مهم. بعض المنتجات على أمازون ونون تجي بضمان دولي فقط، وهذا يصعّب الصيانة محلّياً. تحقّق دائماً من نوع الضمان قبل أجهزة بقيمة ١٠٠٠+ ريال.

