قبل أن تفتح موقع نون أو تدخل معرض، اجلس عشر دقائق وأجب على هذه الأسئلة بصدق. الإجابات هي التي ستحدد الميزانية، الموديل، وحتى التوقيت — وليس العكس.

**١. كم ساعة تستخدم الهاتف يومياً؟** افتح إعدادات > Screen Time (آيفون) أو Digital Wellbeing (أندرويد) وشوف الرقم الفعلي. إذا أنت تحت ٣ ساعات يومياً، أنت مستخدم خفيف — لا تحتاج فلاجشب. إذا فوق ٦ ساعات، أنت مستخدم ثقيل — البطارية الكبيرة والمعالج الكفؤ ليسا رفاهية.

**٢. ما هي أهم ٣ تطبيقات في يومك؟** لو الإجابة WhatsApp، Twitter، YouTube — أي هاتف بـ١٫٨٠٠ ريال يخدمك. لو الإجابة PUBG Mobile، Lightroom، CapCut، وتطبيقات بنوك متعددة — أنت تحتاج معالج فئة عليا و٨ جيجا رام على الأقل. لو من ضمنها تطبيقات تصميم احترافية أو ألعاب ثقيلة، فكّر في ١٢ جيجا رام.

