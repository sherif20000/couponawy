## ٢. اقرأ التقييمات كقارئ محترف، لا كمتسوّق عابر

التقييمات الجيدة قد توفّر عليك ٣ إرجاعات في السنة. لكن قراءة "٤.٥ نجمة من ٥" لا تساوي شيئاً. التقييم الجيد علم، إليك المنهج.

**ركّز على Verified Purchase فقط**: كل المتاجر الكبرى ([أمازون السعودية](/stores/amazon-sa)، [نون](/stores/noon)، [نمشي](/stores/namshi)) تعرض فلتر "مشترٍ موثّق". فعّله. التقييمات غير الموثّقة تشمل المراجعات المدفوعة والمنافسين والمتطفّلين.

**اقرأ تقييمات ٣ و٤ نجوم، تجاهل الـ٥ والـ١**: التقييمات بـ٥ نجوم في الغالب من أناس فرحون لا يلاحظون التفاصيل، أو من حسابات تسويقية. التقييمات بنجمة واحدة من ناس غاضبين لأسباب لا علاقة لها بالمنتج (تأخّر شحن، مشكلة مع المندوب). أصدق الفئات هي التقييمات بين ٣ و٤ نجوم: شخص أعجبه المنتج بشكل عام لكن لاحظ نقاط محدّدة. هذه ذهب.

**استخدم البحث داخل التقييمات**: معظم المتاجر تسمح بالبحث في التقييمات بكلمة. ابحث عن: "runs small" أو "صغير"، "runs large" أو "كبير"، "fabric thin" أو "قماش رقيق"، "color different" أو "اللون مختلف"، "shrinks" أو "ينكمش"، "see through" أو "شفّاف". خمس كلمات تكشف ٨٠٪ من مشاكل المنتج.

**أعطِ وزناً أكبر لمن يشبهك**: لو طولك ١٧٥ ووزنك ٧٥ كغ، تقييم من شخص ١٧٥/٧٥ يكتب "المقاس M ضيّق علي" يساوي ١٠٠ تقييم من ناس مختلفين. كثير من المتاجر العالمية (ASOS مثلاً) تعرض طول ووزن المراجع. لو متاح، فلتر عليه.

**علامات التقييم المزيّف**:

- صيغة "أفضل منتج اشتريته في حياتي، أنصح به بشدّة" بدون أي تفصيل.
- حساب جديد لديه تقييم واحد فقط (هذا).
- تقييم طويل جداً بلغة فصيحة غير طبيعية لتقييم ملابس.
- صور المنتج هي نفس صور المتجر الرسمية (التقييم الحقيقي يصوّر بإضاءة المنزل).
- ٥ تقييمات بنفس الصيغة بأسماء مختلفة في نفس اليوم.

**لا تثق بمتجر تحته أقل من ٥٠ تقييم**: العيّنة الصغيرة لا تكفي. اعتبر المنتج "غير مختبر" حتى لو معدّله ٥ نجوم.

