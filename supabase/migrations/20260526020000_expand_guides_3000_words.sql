## المرحلة ٤: قبل أسبوعين — الفندق والإقامة

التذكرة محجوزة، الوجهة محدّدة، الآن تركيز على الإقامة. ١٤ يوم قبل السفر هي الفترة المثلى لأن أسعار الفنادق غالباً تنخفض قرب التاريخ (الفنادق تفضّل ملء الغرف بسعر أقل على تركها فارغة).

### المقارنة الثلاثية: Booking, Agoda, مباشرة

اقتربت من الحجز؟ لا تحجز من أول موقع. قاعدة عملية:

١. **Booking.com**: ابحث، اقرأ المراجعات، اختر الفندق.
٢. **Agoda**: تحقّق من نفس الفندق بنفس التواريخ. غالباً أرخص ٥-١٥٪ لوجهات آسيا.
٣. **موقع الفندق المباشر**: ابحث على Google باسم الفندق + "official site". غالباً أرخص ٣-١٠٪ مع مزايا (فطور مجاني، واي فاي، انتقالات).

السعر النهائي = الأقل من الثلاثة + كوبون إن وُجد.

### Airbnb مقابل الفندق: متى يفوز كل واحد؟

- **Airbnb يفوز** إذا:
  - عائلة ٤+ أفراد (شقة غرفتين بنصف سعر غرفتين فندق)
  - الإقامة طويلة (+٧ أيام، خصومات الإقامة الطويلة ٢٠-٤٠٪)
  - تريد مطبخ (الطبخ يوفّر ٥٠٪ من ميزانية الطعام)
  - مجموعة أصحاب ٦+ شخص

- **الفندق يفوز** إذا:
  - رحلة قصيرة ٢-٣ ليالي
  - تريد فطور مجاني وخدمة يومية
  - أمان للنساء المسافرات منفردات
  - موقع مركزي قريب من المعالم

### تطبيقات Last-Minute

HotelTonight و Hotwire يعرضون غرف اللحظة الأخيرة (نفس اليوم لـ٧ أيام) بخصم ٢٠-٥٠٪. مفيد لو رحلتك مرنة. لكن لا تعتمد عليه إذا الموسم ذروة، الغرف بتنفد قبل الخصم.

### الشقق الفندقية: التوفير الذكي

في تركيا، مصر، جورجيا، ماليزيا — الشقق الفندقية (Aparthotel) توفّر ٤٠-٥٠٪ مقارنة بفندق ٤ نجوم. تحصل على:

- غرفتين أو ٣ بسعر غرفة فندق
- مطبخ (وفّر على الإفطار والعشاء)
- غسالة (وفّر على شنطة إضافية)
- مساحة مريحة للعمل/الراحة

ابحث على Booking بكلمة "apart hotel" أو "residence" أو "serviced apartment".

### التفاوض المباشر مع الفندق

تقنية يعرفها قليلون: أرسل إيميل للفندق مباشرة قبل الحجز. الرسالة:

> "السلام عليكم، أخطّط للإقامة عندكم من ١٥ إلى ٢٠ مارس (٥ ليالي، غرفتين). رأيت السعر على Booking ٣٫٢٠٠ ريال شامل. هل ممكن سعر أفضل لو حجزت مباشرة؟ شكراً."

الفنادق تدفع عمولة ١٥-٢٥٪ لـ Booking. لو حجزت مباشرة، تقدر تتقاسم العمولة. ٤٠٪ من الفنادق ترد بسعر أفضل.

### الموقع المتميّز vs الموقع المريح

خطأ شائع: حجز فندق "قريب من المعالم" بدون قراءة المنطقة. مثال إسطنبول:

- **الموقع المتميّز (شكلياً)**: ميدان تقسيم، السلطان أحمد. قريب جداً من المعالم، لكن صاخب، سياحي مفرط، مطاعم غالية، ضوضاء طوال الليل.
- **الموقع المريح (واقعياً)**: شيشلي، نيشانتاشي، كاديكوي. ١٠-٢٠ دقيقة مترو من المعالم، لكن حي راقي، مطاعم محلية، أمان، أسعار معقولة.

نفس النصيحة لدبي (التحفّظ على فنادق وسط دبي مقابل البر شا)، القاهرة (الزمالك مقابل الحسين السياحي)، تايلاند (سوكومفيت ٢١-٤٩ مقابل خاوسان روود).

### الرسوم المخفية: انتبه قبل الدفع

- **ضريبة المدينة (City Tax)**: ٥-٣٠ ريال للشخص لليلة في أوروبا، تدفع كاش عند الوصول.
- **رسوم الواي فاي**: في الفنادق الفاخرة أحياناً ٢٠-٥٠ ريال يومياً.
- **Resort Fee**: في المالديف، دبي، فلوريدا — ٥٠-٢٠٠ ريال يومياً غير معلنة في السعر الأساسي.
- **رسوم خزنة الغرفة، صالة رياضية، تنظيف يومي**: اقرأ التفاصيل قبل الحجز.
- **رسوم الانتقالات من المطار**: "شامل النقل من المطار" يعني أحياناً ذهاب فقط، أو عبر فان مشترك مع توقّفات.

## المرحلة ٥: في الوجهة — التوفير اليومي

وصلت. التخطيط ما خلص — الوجهة فيها قرارات يومية كل واحد منها يوفّر أو يضيع ١٠٠-٣٠٠ ريال.

### الطعام: ٣ قواعد بسيطة

١. **ابتعد ١٥٠ متر عن المعلم السياحي**. كل مطعم في الشارع المؤدّي للمعلم سعره مضاعف. ابتعد شارعين، السعر ينصف.
٢. **اتبع الناس المحليين، تجاهل المراجعات السياحية**. مطعم في تركيا بـ٢٠٠ مراجعة عربية وصينية = سياحي. مطعم بـ٥٠٠ مراجعة تركية = محلي وأرخص.
٣. **الإفطار في الشقة، الغداء في الشارع، العشاء في مطعم لائق**. هذه القسمة توفّر ٥٠٪ من ميزانية الطعام بدون التضحية بالتجربة.

### التنقّلات: المترو ملك، الأوبر ملكة

- **المترو/المواصلات العامة**: ٥-١٥ ريال يومياً غير محدود. الأوبر ٢٠-٤٠ ريال للرحلة الواحدة. الفرق على ٧ أيام = ٣٠٠-٥٠٠ ريال.
- **تأجير سيارة**: يستحق فقط في الوجهات الجبلية أو الجزر (جورجيا الجبلية، اليونان الجزر، أنطاليا الريفية). لا تستأجر في إسطنبول، القاهرة، بانكوك — الازدحام رهيب والمترو أسرع.
- **تطبيقات نقل محلية**: Bolt في أوروبا، Grab في آسيا، Careem في الخليج. أرخص ٢٠-٣٠٪ من Uber.

### العملة: لا تصرف في المطار أبداً

صرّافات المطار أسوأ سعر في الوجهة. الفرق يصل لـ٧-١٢٪. خياراتك:

- **بطاقة بنكية بدون رسوم تحويل عملة**: Wise، Revolut، حسابات بنوك سعودية (بنك الراجحي، الأهلي عندهم بطاقات سفر) — السعر هو سعر السوق الفعلي.
- **صرف في وسط المدينة**: ابحث على Google عن "best money exchange + اسم المدينة". الصرّافات المحلية بعيداً عن المطار أرخص ٥-٨٪.
- **ATM في بنك (ليس في المطار)**: السعر مقبول، لكن انتبه لرسوم بنكك السعودي (قد تكون ٢٠-٣٠ ريال للسحب).
- **لا تستخدم صرّافات المطار**: لو مضطر، اصرف ١٠٠-٢٠٠ ريال فقط للتاكسي والوصول للفندق.

### SIM Card محلية: التوفير الكبير

التجوّال من شركتك السعودية: ١٥-٣٠ ريال يومياً. سيم محلية: ٣٠-٨٠ ريال للأسبوع كامل مع إنترنت غير محدود. التوفير على رحلة ٧ أيام: ١٥٠-٢٠٠ ريال.

اشترِ السيم من سوبر ماركت أو متجر اتصالات في وسط المدينة، ليس من المطار (المطار أغلى ٣ أضعاف). أو استخدم eSIM (Airalo، Holafly) — تشتري من السعودية وتفعّل عند الوصول.

### تذاكر المتاحف و"City Pass"

City Pass (Istanbul Pass, Paris Museum Pass, Bangkok Card) يبدو موفّراً، لكن انتبه:

- يستحق فقط لو خطّطت لزيارة ٦+ معالم في أيام قليلة.
- لو رحلتك مريحة وعندك ٣-٤ معالم فقط، شراء التذاكر منفردة أرخص.
- بعض الـPass يشمل وسائل نقل ومتاحف بسعر عادل، اقرأ التفاصيل.

### تطبيقات الخصم المحلية

- **Klook**: قوي في آسيا (تايلاند، ماليزيا، اليابان، إندونيسيا، فيتنام). جولات، تذاكر، انتقالات بخصم ١٠-٣٠٪.
- **GetYourGuide**: قوي في أوروبا. تذاكر متاحف، جولات سيرة، نقل بأسعار معقولة.
- **Viator**: شامل عالمياً، جيد للجولات المنظّمة.
- **تطبيقات محلية**: كل وجهة عندها تطبيق محلي. مثال: Yandex Go في باكو وتبليسي للنقل.

### نصيحة ATM الذهبية

لا تستخدم بطاقتك في أول ATM تراه في المطار. الأسباب:

- أسوأ سعر صرف (٥-١٠٪ تحت السوق).
- بعضها يفرض رسوم "خدمة" ٢٠-٤٠ ريال للسحب.
- خطر التزوير (Skimming).

اسحب من ATM داخل بنك في وسط المدينة. الفرق على ٢٫٠٠٠ ريال = ١٠٠-٢٠٠ ريال.

## التأمين الطبي السفري — لا تتجاهله

أرخص قرار ذكي في الرحلة. ٥٠-١٥٠ ريال للأسبوع للشخص، قد توفّر آلاف الريالات لو حصل طارئ.

### كم يكلّف فعلاً؟

- **تأمين أساسي (٧ أيام، الشخص)**: ٥٠-٨٠ ريال
- **تأمين شامل (٧ أيام، الشخص)**: ١٠٠-١٥٠ ريال
- **تأمين عائلي (٤ أفراد، ٧ أيام)**: ٢٠٠-٤٠٠ ريال

### ماذا يغطّي؟

- **الأساسي**: الطوارئ الطبية، الإسعاف، الإقامة في المستشفى حتى حد معيّن (عادةً ٥٠٫٠٠٠-١٠٠٫٠٠٠ ريال).
- **الشامل**: ما سبق + إلغاء الرحلة، تأخير الرحلة، فقدان الأمتعة، فقدان الجواز، إخلاء طبي.

### مقارنة شركات تأمين سعودية رئيسية

| الشركة | السعر الأساسي ٧ أيام للشخص | المميّزات |
|---|---|---|
| التعاونية | ٥٥-٨٥ ريال | تغطية واسعة، شبكة مستشفيات عالمية |
| ميدغلف | ٤٥-٧٠ ريال | الأرخص، تغطية أساسية جيدة |
| أكسا الخليج | ٦٠-٩٠ ريال | تغطية تجارية وسياحية، مرنة |
| بوبا العربية | ٧٠-١٠٠ ريال | الأقوى في تغطية المستشفيات |

### تأمين الإلغاء: متى يستحق؟

أضِف "تأمين الإلغاء" (٢٠-٤٠ ريال إضافية) إذا:

- الرحلة غالية (+١٠٫٠٠٠ ريال).
- ظروفك العائلية أو الصحية غير مستقرّة.
- الوجهة عندها مخاطر طقس (أوروبا في الشتاء، آسيا في موسم الأمطار).

لا يستحق لرحلة ٢٫٠٠٠-٣٫٠٠٠ ريال إلا لو وضعك الشخصي يستلزم.

### تأمين شنغن مقابل تأمين عام

تأمين شنغن إلزامي للسفر لأوروبا (تغطية ٣٠٫٠٠٠ يورو). تأمين عام للسفر لباقي الدول، الحد أقل والأسعار أرخص. تأكّد من نوع التأمين المطلوب قبل الحجز.

