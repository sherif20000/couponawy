من يحتاج هذا الدليل؟ كل من اشترى مرة وأحبط، كل من يخطّط لتجديد خزانة الموسم، وكل من يريد تحويل التسوّق أونلاين من قمار عشوائي إلى عملية محسوبة.

## ١. اعرف مقاساتك بدقة — ليس بالعين، بالشريط

أكبر مصدر لإرجاع الملابس عالمياً ليس عيوب التصنيع ولا الألوان المختلفة عن الصورة — بل أن المقاس "M" عند زارا ليس نفسه عند شي إن ولا عند نمشي. والمتسوّق العادي يطلب "مقاسه المعتاد" ثم يفاجأ. الحل ليس الذاكرة، الحل شريط القياس.

### كيف تقيس جسمك خطوة بخطوة

اشترِ شريط قياس قماشي بـ١٠ ريالات من أي مكتبة، وقم بالقياس على ملابس داخلية فقط (الملابس الفوقية تضيف ٢-٣ سم). قِس مرتين وخذ المتوسّط. سجّل القياسات في ملاحظة على هاتفك واسمها "مقاساتي - ٢٠٢٦" لتتجنّب القياس كل مرة.

**للرجال — ٦ قياسات أساسية:**

- **الصدر**: ضع الشريط تحت الإبطين مباشرة، يدور حول الجزء الأعرض من الصدر، موازياً للأرض تماماً. اترك إصبعك تحت الشريط لتجنّب الشدّ.
- **الخصر**: قِس عند مستوى السرّة، ليس عند مكان حزام البنطال (هذا "الورك العلوي"، أصغر برقمين عادة).
- **الورك**: عند أعرض نقطة في الأرداف، الواقفة قدميك معاً.
- **طول الساعد**: من منتصف الجزء الخلفي من الرقبة، عبر الكتف، حتى عظمة الرسغ. أهم قياس للقمصان الرسمية.
- **طول الساق الداخلي (Inseam)**: من أعلى الفخذ الداخلي حتى الكاحل. اقصر ٢ سم لو تريد ينتهي عند الكاحل، اقصر ٤ سم لو تريد "Cropped".
- **رقبة القميص**: حول قاعدة الرقبة عند تفاحة آدم، أضف ١ سم للراحة.

**للنساء — ٥ قياسات أساسية:**

- **الصدر (الأعلى)**: على أعرض جزء، تحت الإبطين.
- **تحت الصدر**: مباشرة تحت خط الصدر، حول القفص الصدري. هذا القياس مع "الصدر الأعلى" يحدّد مقاس حمّالة الصدر ومقاس البلوزات المخصّرة.
- **الخصر**: أضيق نقطة بين الصدر والورك (عادة فوق السرّة بـ٣-٤ سم).
- **الورك**: عند الجزء الأعرض، عادة ٢٠ سم تحت الخصر.
- **طول الساق**: من أعلى الفخذ الداخلي حتى الكاحل، نفس طريقة الرجال.

**للأطفال — قاعدة ذهبية**: العمر على الملصق (٣-٤ سنوات، ٥-٦ سنوات) **استرشادي فقط**. طفل بعمر ٤ سنوات قد يلبس مقاس ٥-٦. الطريقة الصحيحة: قِس **طول الطفل بالسنتيمتر من رأسه إلى أخمص قدميه**، ومحيط صدره، ثم قارن بجدول المتجر. أضف قياس **محيط الكفّ** للقمصان طويلة الكمّ. للحذاء: قِس طول القدم من الكعب إلى أطول إصبع (عادة الإبهام).

