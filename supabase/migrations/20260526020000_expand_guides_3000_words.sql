## أخطاء يقع فيها المسافرون الجدد

كل خطأ من هذه الأخطاء تكرّر عشرات المرات وله تكلفة محسوبة:

١. **حجز الفندق قبل التذكرة** — اكتشفت أن تذكرة ذلك التاريخ غالية، اضطررت لتغيير الفندق وخسرت ٢٠٠-٥٠٠ ريال غرامة إلغاء.

٢. **تجاهل رسوم Airbnb المخفية** — السعر الأساسي ١٫٠٠٠ ريال، تضيف رسوم تنظيف ٢٠٠ + رسوم خدمة ١٥٠ + ضريبة مدينة ١٠٠ = الإجمالي ١٫٤٥٠. اقرأ التفاصيل قبل الدفع.

٣. **شراء سيم كارت في المطار** — ٢٠٠ ريال في المطار، ٥٠ ريال في وسط المدينة. الفرق ١٥٠ ريال.

٤. **رفض تأمين الإلغاء على رحلة غالية** — رحلة ٨٫٠٠٠ ريال، طارئ عائلي، خسرت ٣٫٠٠٠ غرامة. التأمين كان ٨٠ ريال.

٥. **عدم التحقّق من تأشيرة الترانزيت** — رحلة دبي-طوكيو عبر بانكوك، احتجزت في بانكوك ٨ ساعات لأنك لا تملك تأشيرة عبور، خسرت رحلة الترانزيت.

٦. **الاعتماد على Wi-Fi المطار لتحميل الخرائط** — وصلت، البطارية ٢٠٪، الواي فاي ضعيف، الخرائط ما حُمّلت، أخذت تاكسي مجهول ودفعت ٣ أضعاف السعر العادل.

٧. **نسيان شاحن عالمي (Universal Adapter)** — شراؤه في فندق دبي ١٥٠ ريال، شراؤه من السعودية قبل السفر ٣٥ ريال.

٨. **حجز رحلة "حزمة" بدون مقارنة** — "تذكرة + فندق + ترانسفير بـ٥٫٠٠٠ ريال" قد تكون فعلاً ٣٫٨٠٠ ريال لو حجزت كل قطعة منفصلة.

٩. **عدم تصوير الجواز والوثائق رقمياً قبل السفر** — فقدان الجواز في الوجهة بدون نسخة احتياطية يكلّف يومين توقّف في السفارة. مع نسخة، نصف يوم.

١٠. **تأجيل سحب الفلوس للوصول** — صرّافة المطار سعرها سيّئ، ATM المطار رسومه عالية. الحل: اسحب ٥٠٠-١٫٠٠٠ ريال بعملة الوجهة من بنكك السعودي قبل السفر بأيام لتغطية أول ٢٤ ساعة.

## الأسئلة الشائعة

### السؤال: متى أحجز التذكرة لأحصل على أرخص سعر فعلاً؟

من تحليل بيانات شركات الطيران، النقطة المثلى للحجز للوجهات الإقليمية (تركيا، مصر، الإمارات) هي ٤-٦ أسابيع قبل السفر. للوجهات البعيدة (أوروبا، آسيا الشرقية) هي ٨-١٢ أسبوع. الحجز قبل ١٢ أسبوع غالباً لا يضيف توفير، والحجز قبل أسبوعين السعر يقفز ٣٠-٥٠٪.

### السؤال: هل التطبيقات الموفّرة مثل Hopper موثوقة؟

Hopper موثوق في توقّع الأسعار (دقّة ٩٥٪)، لكن أحياناً عمولاته أعلى من Google Flights و Skyscanner. استخدمه لتوقّع "السعر سيرتفع أم ينخفض"، واحجز من المنصّة الأرخص بعد التأكّد.

### السؤال: أيهما أوفر، حزمة (تذكرة + فندق) أم الحجز منفصل؟

الحجز المنفصل أوفر ٧٠٪ من الحالات. الحزم تبدو موفّرة لأن السعر مدمج، لكن لو فصلت قطع الحزمة لاكتشفت أنها أغلى ١٠-٢٠٪. استثناء: حزم رحلات شركات الطيران الرسمية (Emirates Holidays, Saudia Holidays) قد توفّر في فترات العروض.

### السؤال: متى الموسم الميت لكل وجهة شائعة من السعودية؟

- **تركيا**: نوفمبر-فبراير (الإلا الكريسماس وأعياد رأس السنة)
- **دبي**: مايو-سبتمبر (الحر)
- **مصر**: يونيو-أغسطس (الحر)
- **جورجيا**: نوفمبر-مارس (البرد)
- **المالديف**: مايو-سبتمبر (موسم الأمطار)
- **تايلاند**: مايو-أكتوبر (موسم الأمطار)
- **اليونان**: نوفمبر-مارس

الفرق في السعر بين الموسم الميت وموسم الذروة قد يصل لـ٦٠٪.

### السؤال: هل البطاقة الائتمانية تفيد فعلاً في السفر؟ أيها؟

نعم، البطاقات الائتمانية في السفر مفيدة لـ٣ أسباب: حماية الشراء، ميل/نقاط، تأمين أساسي. الأفضل في السعودية: بطاقة الراجحي تمتاز Air، بطاقة الأهلي World Elite، بطاقة سامبا أمريكان إكسبريس الذهبية. اقرأ شروط النقاط — أحياناً تحتاج ١٠٠٫٠٠٠ نقطة لتذكرة، مما يعني صرف ٥٠٫٠٠٠ ريال على البطاقة.

### السؤال: كيف أحجز رحلة عائلية بـ٤ تذاكر بدون أن يطّر السعر؟

ابحث عن تذكرة واحدة أولاً، تأكّد من السعر، ثم احجز ٤ تذاكر في عملية واحدة. لو حجزت ٤ مرات منفصلة، الخوارزمية ترى "ارتفاع طلب" وترفع السعر. أيضاً، خصومات الأطفال (تحت ١٢ سنة) عادةً ٢٥-٥٠٪ — تأكّد من تطبيقها.

### السؤال: ما الفرق بين الإلغاء المجاني والاسترداد الكامل؟

"الإلغاء المجاني" يعني تلغي الحجز بدون غرامة لكن المبلغ يُسترد كرصيد للموقع، تستخدمه في حجز قادم. "الاسترداد الكامل" يعني المبلغ يرجع لبطاقتك. الفرق مهم لو لم تخطّط لرحلة قادمة قريباً.

### السؤال: متى أصرف العملة قبل السفر ومتى في الوجهة؟

اصرف ٢٠٪ من ميزانية الوجهة قبل السفر (لتغطية أول ٢٤ ساعة + التاكسي من المطار). اصرف ٨٠٪ في وسط مدينة الوجهة (سعر أفضل ٥-٨٪). لا تصرف في المطار أبداً.

### السؤال: هل صور وجوازات الأطفال تتغيّر مع كل سفر للسعودية؟

لا، صورة الجواز صالحة طوال مدة صلاحية الجواز. لكن لاحظ: جوازات الأطفال صلاحيتها ٥ سنوات في السعودية (مقابل ١٠ سنوات للبالغين). تأكّد من صلاحية الجواز ٦ أشهر على الأقل قبل تاريخ السفر.

### السؤال: تأمين بطاقة الائتمان يكفي أم أحتاج تأمين منفصل؟

تأمين بطاقة الائتمان غالباً يغطّي حالات محدودة (إلغاء رحلة، تأخّر أمتعة)، لكن لا يغطّي الطوارئ الطبية بشكل كافٍ. تأمين السفر المنفصل ضروري للتغطية الطبية، خاصةً للسفر لأوروبا (إلزامي شنغن) أو أمريكا (التكاليف الطبية فيها فلكية).

### السؤال: كيف أتعامل مع تأخير الرحلة من ناحية الحقوق؟

في أوروبا، لائحة EU261 تضمن تعويض ٢٥٠-٦٠٠ يورو لتأخير +٣ ساعات. في السعودية، لائحة GACA تضمن تعويض حسب التأخير. خذ توثيق التأخير من بوّابة المطار، اطلب تعويض كتابياً من شركة الطيران بعد الرحلة. شركات مثل AirHelp تأخذ القضية نيابةً عنك مقابل ٢٥٪ من التعويض.

### السؤال: هل أستحق تعويض لو فقدت أمتعتي؟

نعم. اتفاقية مونتريال تضمن تعويض حتى ١٫٢٨٨ SDR (تقريباً ٦٫٤٠٠ ريال) لفقدان الأمتعة. تأخّر الأمتعة يستحق تعويض مصاريف الضروريات (ملابس، أدوات شخصية، حتى ٥٠٠-١٫٠٠٠ ريال). احتفظ بالإيصالات وقدّمها لشركة الطيران خلال ٢١ يوم.

