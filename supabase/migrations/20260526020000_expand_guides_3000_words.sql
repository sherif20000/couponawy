## الفرق الأساسي بين المنصّتين

أمازون السعودية ونون كلاهما يبيعون "كل شي"، لكن طريقة بناء التشكيلة، الأسعار، والشحن مختلفة جذرياً. فهم هالاختلاف هو نقطة البداية لأي قرار شراء ذكي.

### أمازون السعودية: العمق العالمي

أمازون السعودية انطلقت رسمياً سنة ٢٠٢٠ بعد ما استحوذت أمازون على سوق.كوم، وورثت تشكيلة هائلة وعلاقات مع علامات تجارية عالمية. القوة الحقيقية لأمازون مو في الأسعار الأرخص دائماً، بل في **العمق**: تلاقي عندهم منتجات نيش (niche) ما تلاقيها في أي مكان ثاني — كتب أكاديمية إنجليزية متخصّصة، إكسسوارات تصوير احترافية، قطع غيار أجهزة معيّنة.

- **القوة الأساسية**: تشكيلة عميقة، علامات عالمية أصلية، نظام تقييمات أكثر نضجاً، سياسة إرجاع واضحة خلال ٣٠ يوم، خدمة Amazon Renewed للأجهزة المجدّدة.
- **نقاط الضعف**: المنتج المستورد من خارج المخزون السعودي يطوّل في الشحن ٧–١٤ يوم، أحياناً تجي رسوم جمركية إضافية عند الاستلام، وبعض المنتجات تطلع أغلى من نون بفارق ٥–١٥٪ خصوصاً في الموضة والعطور.
- **شحن المنتجات المحلّية**: ٢٤–٤٨ ساعة في المدن الرئيسية (الرياض، جدة، الدمام)، وأحياناً نفس اليوم لمشتركي Prime.
- **شحن المنتجات المستوردة**: ٧–١٤ يوم في الغالب، مع تتبّع كامل وتنبيه إذا تأخّر.
- **مناسب لـ**: الإلكترونيات الراقية، الكتب الإنجليزية، منتجات Amazon Basics منزلية، مستلزمات الأطفال، الكتب الورقية والرقمية، قطع الغيار النادرة.

### نون: السرعة المحلّية

نون بدأت كمنصّة سعودية–إماراتية في ٢٠١٧ وبنت موقعها كلاعب محلّي شرس. ما يحاولون يضاهون أمازون في العمق، بدالها يركّزون على **السرعة والعروض الموسمية**. عروض Yellow Friday في نوفمبر صارت حدث سنوي ينتظره المتسوّق السعودي مثل ما ينتظر الجمعة البيضاء.

- **القوة الأساسية**: عروض موسمية كبيرة (Yellow Friday، رمضان، صيف نون)، تشكيلة محلّية عميقة في الموضة والجمال، شحن سريع داخل السعودية، تطبيق noon Food للوجبات، noon Minutes للبقالة السريعة.
- **نقاط الضعف**: تشكيلة أقل عمقاً في الكتب الإنجليزية المتخصّصة والإلكترونيات الراقية، بعض البائعين الخارجيين أقل التزاماً بمواعيد الشحن.
- **الشحن**: ١–٣ أيام للمنتجات المحلّية، حتى نفس اليوم في الرياض وجدة لمشتركي noon One، و٥–١٠ أيام للمستورد.
- **مناسب لـ**: الموضة الرجالية والنسائية، العطور، مستحضرات التجميل، البقالة، الإلكترونيات الشعبية (هواتف متوسطة، سماعات، أجهزة منزلية صغيرة).

### الفروقات اللي ما ينتبهلها المتسوّق

**طرق الدفع**: المنصّتين تدعمان مدى، فيزا، ماستركارد، Apple Pay، STC Pay، والدفع عند الاستلام (cash on delivery) في أغلب المدن. نون يدعم تابي وتمارا بشكل أكثر سلاسة في الفئات الأرخص، أمازون يدعمهما لكن مع حدّ أدنى أعلى أحياناً.

**خدمة العملاء**: أمازون يردّ خلال ساعات عبر الشات أو المكالمة، وسياسة الإرجاع تلقائية تقريباً للمنتجات اللي تشحنها بنفسها (Sold by Amazon). نون يردّ بسرعة عبر الشات داخل التطبيق، لكن الإرجاع من بائع ثالث يحتاج موافقة البائع وقد يأخذ ٢٤–٤٨ ساعة إضافية.

**تجربة التطبيق مقابل الموقع**: تطبيق أمازون أنظف بصرياً لكن يدفعك للعروض المموّلة. تطبيق نون مزدحم بالعروض الترويجية لكن أسرع في عرض الكوبونات النشطة على المنتج. عموماً، استخدم التطبيق للشراء واستخدم الموقع للمقارنة.

## استراتيجيات التوفير على أمازون السعودية

التوفير على أمازون مو موضوع حظ، بل ست أدوات داخلية إذا استخدمتها بشكل صحيح، توفّر بسهولة ٢٠–٣٥٪ على مشترياتك السنوية.

### ١. كوبونات أمازون داخل الموقع (Amazon Coupons)

كثير من المنتجات تعرض كوبون "وفّر ١٥٪" أو "وفّر ٥٠ ريال" تحت السعر مباشرة. هالكوبون ما يطبّق تلقائياً، لازم تضغط على الـ checkbox قبل ما تضيف للسلة. نصيحة: ادخل قسم "Amazon Coupons" مباشرة من القائمة (أو ابحث في جوجل "amazon.sa coupons")، وفلترها حسب الفئة. تلاقي كوبونات نشطة لمنتجات ما كنت تفكّر فيها، لكن السعر بعد الكوبون يخلّيها صفقة فعلية.

### ٢. اشترك ووفّر (Subscribe & Save)

إذا تشتري نفس المنتج بشكل دوري — حفّاضات، شامبو، مكمّلات غذائية، قهوة — اشترك في خدمة Subscribe & Save. الخصم يبدأ من ٥٪ ويصل إلى ١٥٪ إذا اشتركت في ٥ منتجات أو أكثر تجي في نفس الشحنة الشهرية. الفئات اللي تشتغل معها الخدمة في السعودية محدودة (بقالة، صحة، عناية شخصية، حفّاضات، طعام حيوانات أليفة). الفخ: إذا نسيت تلغي الاشتراك بعد ما تكفي حاجتك، يجيك المنتج ويُخصم من بطاقتك تلقائياً. اضبط تذكير في التقويم قبل تاريخ الشحنة بـ ٤٨ ساعة.

### ٣. عروض البرق (Lightning Deals)

عروض محدودة الوقت (٤–٦ ساعات عادة) أو محدودة الكمّية. الخصم يتراوح بين ١٠٪ و٤٠٪ على منتجات إلكترونيات، أجهزة منزلية، وملابس. خطوات الاستفادة منها:

- فعّل إشعارات تطبيق أمازون لـ "Lightning Deals" من إعدادات التطبيق.
- أضف المنتجات اللي تتابعها إلى قائمة الرغبات (Wishlist) — التطبيق يبلّغك لو نزل عليها عرض.
- خصّص جلسة تصفّح كل أسبوع يوم الجمعة الصباح، وقت ما تنطلق أغلب العروض الأسبوعية.

### ٤. صندوق الشراء و"بائعون آخرون" (Buy Box)

كثير من المنتجات في أمازون يبيعها أكثر من بائع. الزر الأخضر "اشترِ الآن" يطلع تلقائياً للبائع الفائز بـ Buy Box (عادة بسبب السعر أو سرعة الشحن)، لكن في زر صغير تحت السعر اسمه "بائعون آخرون" أو "عروض جديدة من ٥". اضغطه، رح تلاقي أحياناً نفس المنتج بسعر أقل من بائع ثاني. **متى يكون البائع الثالث آمن؟** عندما يكون "Sold by [اسم البائع] and Fulfilled by Amazon" — يعني المنتج في مخازن أمازون وسياسة الإرجاع نفسها. تجنّب البائعين اللي عندهم تقييم أقل من ٩٠٪ أو عدد تقييمات أقل من ٥٠.

### ٥. أمازون المجدّد (Amazon Renewed)

منتجات إلكترونيات مجدّدة بشهادة من أمازون: هواتف، لابتوبات، سماعات، ساعات ذكية. الخصم يتراوح بين ١٥٪ و٤٠٪ مقارنة بالجديد، مع ضمان ٩٠ يوم على الأقل من أمازون نفسها. **متى ذكي؟** للأجهزة اللي ما تتطلّب آخر إصدار — لابتوب عمل عادي، آيباد لقراءة الكتب، سماعات Bluetooth. **متى خطر؟** للهواتف الراقية اللي عمرها الافتراضي قصير على البطارية، أو لمنتجات التجميل والعناية الشخصية (طبعاً ما تباع مجدّدة، لكن انتبه).

### ٦. اشتراك Prime كمبرّر تكلفة

Prime في السعودية يكلّف ١٦ ريال شهرياً أو ١٤٠ ريال سنوياً. مزاياه: شحن مجاني وسريع، Prime Video (مكتبة أفلام ومسلسلات)، عروض حصرية على Lightning Deals، Prime Reading لبعض الكتب. **حساب التعادل البسيط**: إذا تطلب من أمازون أكثر من ٤ مرّات شهرياً بقيمة أقل من ٢٠٠ ريال للطلب الواحد (الحدّ الأدنى للشحن المجاني)، Prime يوفّر عليك تكلفة الشحن أكثر من قيمة الاشتراك. أضف عليه قيمة Prime Video لو فعلاً تستخدمه، وتطلع المعادلة مربحة.

## استراتيجيات التوفير على نون

نون مبنية على منطق تسعير مختلف — العروض تجيب الزبون، والاشتراكات تخلّيه يرجع. ست استراتيجيات للاستفادة القصوى:

### ١. اشتراك noon One

noon One يكلّف ٥٩ ريال سنوياً (آخر تسعير معروض)، وأرخص بكثير من Prime. مزاياه: شحن مجاني بدون حدّ أدنى للطلبات المؤهّلة، خصومات حصرية للأعضاء على كثير من المنتجات، أولوية في عروض Yellow Friday. **حساب التعادل**: إذا تشتري من نون ٣ مرّات في السنة بشحن مدفوع، الاشتراك يدفع نفسه. أغلب المتسوّقين المنتظمين يصلون لهالعدد بسهولة.

### ٢. الجمعة الصفراء (Yellow Friday)

تنطلق سنوياً في نوفمبر وتسبق Black Friday العالمية ببضعة أيام. أهم نصائح الاستعداد:

- ابدأ من أكتوبر بإنشاء قائمة رغبات (Wishlist) للمنتجات اللي تبيها. نون يراقب الـ Wishlists ويخفّض الأسعار على المنتجات اللي عليها طلب كثير.
- لا تشتري المنتج اللي تبيه في أوّل يوم — راقب السعر ٢٤ ساعة. كثير من المنتجات تنزل أكثر في اليوم الثاني أو الثالث.
- استخدم أداة مقارنة الأسعار التاريخية: قبل تشتري، ابحث عن المنتج في جوجل بكلمة "[اسم المنتج] noon price history" وشوف إذا فعلاً السعر الحالي أقل من المعتاد.
- جهّز طرق الدفع قبل ساعة الذروة — إضافة بطاقة جديدة وقت الازدحام أحياناً يفشل.

### ٣. nooon Food والخصومات المتبادلة

إذا تشترك في noon One، تحصل على خصومات إضافية على noon Food (تطبيق توصيل المطاعم). كذلك بعض الكوبونات تشتغل بشكل متبادل بين نون التسوّق ونون Food. تابع قسم "كوبوناتي" داخل التطبيق بانتظام.

### ٤. محفظة نون (noon Wallet) والاسترداد النقدي

عند الإرجاع، نون يقترح ترجيع المبلغ لـ noon Wallet بدلاً من البطاقة، وأحياناً يضيف ٥–١٠٪ كحافز. خذها لو كنت تشتري من نون بشكل منتظم — الفلوس في المحفظة تجيب لك خصومات إضافية وأحياناً عروض حصرية على المنتجات اللي تدفعها من الرصيد.

### ٥. nooon Minutes للبقالة السريعة

التوصيل خلال ١٥–٣٠ دقيقة لمنتجات البقالة في المدن الرئيسية. الأسعار أحياناً تطلع أقل من السوبرماركت التقليدي خلال عروض نهاية الأسبوع، خصوصاً على المنتجات اللي تنتهي صلاحيتها قريباً (مع ذلك الصلاحية المتبقّية كافية للاستخدام العادي). قبل تطلب من تطبيق توصيل ثاني، تحقّق من noon Minutes أولاً.

### ٦. تجميع الكوبونات (Coupon Stacking)

نون يسمح أحياناً بدمج كوبون منصّة + كوبون بائع + خصم noon One. القاعدة العامة: الكوبونات النسبية (مثل "خصم ١٠٪") عادة لا تتراكم مع بعض، لكن الكوبونات بقيمة ثابتة (مثل "خصم ٢٠ ريال") قد تتراكم مع خصم النسبة. اختبر قبل الدفع: ضع المنتج في السلة، طبّق الكوبون الأول، ثم حاول تطبيق الثاني — لو رفض، النظام رح يقول لك بوضوح. لا تستسلم من المحاولة الأولى. تصفّح [كوبونات نون الفعّالة](/stores/noon) قبل كل عملية شراء.

